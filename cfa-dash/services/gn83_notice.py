GN83_NOTICE_CONTEXT = """
Government Notice No. 83 was published on 20 March 2026 as the Tanzania
Shipping Agencies (Fees for Clearing and Forwarding Services) Order, 2026.
It applies to clearing and forwarding agents registered by the Corporation
and to regulated clearing and forwarding services for import, export, and
transit cargo.

Key definitions:
- Bill of Lading (BL): carrier-issued document confirming receipt of cargo
  and title to goods.
- Clearing and forwarding agent: a company registered by the Corporation to
  provide clearing and forwarding agency services.
- Minimum agency fees: minimum charges prescribed in the Schedule.

Professional duties include:
- Preparing, verifying, submitting, and processing customs declarations and
  supporting documents.
- Advising on documentation, duties, taxes, levies, charges, fees, and trade
  terms.
- Facilitating payment of duties, taxes, levies, port charges, and statutory
  fees.
- Coordinating transport, handling, warehousing, logistics providers, cargo
  packing, insurance, and compliance obligations.
- Maintaining proper and accurate shipment, documentation, and financial
  records.

Minimum agency fee rule:
- A clearing and forwarding agent shall not charge below the minimum agency
  fees in the Schedule.
- Charging above the minimum is allowed.

Exemptions:
- Commodities subject to statutory price regulation by other sector regulators,
  including fertiliser, petroleum, and sugar.
- Approved in-house clearance arrangements.
- Any other cargo category determined by the Corporation.
- Exemption from minimum fees does not exempt the agent from other regulatory
  obligations.

Mandatory compliance:
- Issue an official receipt or tax invoice for services rendered.
- Use relevant prescribed regulatory and customs systems.
- Accurately report declared service charges in prescribed electronic systems.
- Maintain proper books of account.
- Retain records for a minimum of five years.
- Pay all lawful charges necessary for operation of the firm.

Monitoring, review, complaints, penalties:
- The Corporation monitors compliance and may inspect or request information.
- Minimum fees may be reviewed from time to time.
- Aggrieved persons may lodge complaints under applicable complaints handling
  regulations.
- Contravention is an offence liable to penalties under the Act.

Schedule:
- Import, Export, and Transit shipment tables prescribe minimum agency fees in
  USD-equivalent Tanzania shillings.
- Sea/Inland Waterways, Road Transport (Border), and Air Transport are covered.
"""
